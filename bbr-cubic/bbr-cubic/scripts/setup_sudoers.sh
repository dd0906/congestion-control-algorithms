#!/usr/bin/env bash
# One-time provisioning script: grants the WSL user passwordless sudo for ONLY the
# two operations this replication project actually needs to run automatically and
# repeatedly, with no wildcards anywhere (this sudo build rejects wildcard argument
# matching outright — "wildcards are not allowed in command arguments" — so every
# entry below is a fully literal command).
#
# Scope granted (see docs/PROJECT_PLAN.md Phase 4 for why each is needed):
#   1. modprobe tcp_bbr (exact, no args to vary)
#        -> loads the BBR congestion-control kernel module. Once loaded, any
#           process can select it per-socket (iperf3 -C bbr) with no further
#           privilege, so this is the only BBR-related sudo needed.
#   2. python3 <one of a small fixed set of project entrypoint scripts>, with
#      NO trailing arguments
#        -> Mininet requires its top-level process to run as root (it creates
#           network namespaces/veths itself); everything Mininet does
#           internally (ip, tc netem, etc.) happens as subprocess calls from
#           that already-root process, so no separate ip/tc/sysctl sudo entries
#           are needed. Each script takes no CLI flags — every experiment
#           parameter (duration, QACK interval, RTTs, ...) is a fixed constant
#           matching the paper, so there is nothing to wildcard and no
#           flexibility is lost.
#
# Explicitly NOT granted here (by design, to keep scope minimal):
#   - apt-get/apt install: this is a one-time bulk setup step, not something
#     that needs to run unattended/repeatedly, so it is run interactively by
#     the user instead (see docs/NEXT_TASK.md for that command when Phase 4
#     reaches it). No wildcard-free way to pre-authorize an arbitrary package
#     list without enumerating every package literally, which would be more
#     fragile, not less.
#   - ip/tc/sysctl as standalone sudo commands: not needed, see above.
#   - Any unscoped shell, editor, or interpreter invocation.
#
# Safe by construction: the rule is written to a temp file and the FULL
# candidate sudoers file is checked with `visudo -c -f` BEFORE anything is
# installed. If invalid, nothing is touched. After install, the whole sudoers
# database is re-validated with `sudo visudo -c`.

set -euo pipefail

SUDO_USER_NAME="$(whoami)"
PROJECT_SCRIPTS_DIR="/mnt/c/Users/PRAVEENA/OneDrive/Desktop/FairFlow_Replication/scripts"
RULE_FILE="/etc/sudoers.d/fairflow-minimal"
TMP_FILE="$(mktemp)"

# Fixed, literal entrypoint scripts (created later in Phase 4/5). Each is invoked
# as `sudo python3 <path>` with no arguments — nothing else matches this alias.
cat > "$TMP_FILE" <<EOF
# FairFlow Replication project — minimal passwordless sudo scope.
# Generated by scripts/setup_sudoers.sh — do not hand-edit without re-validating
# with 'visudo -c'. Contains no wildcards (this sudo build disallows them).

Cmnd_Alias FAIRFLOW_MODPROBE = /usr/sbin/modprobe tcp_bbr
Cmnd_Alias FAIRFLOW_RUN = /usr/bin/python3 ${PROJECT_SCRIPTS_DIR}/run_smoketest.py, /usr/bin/python3 ${PROJECT_SCRIPTS_DIR}/run_baseline.py, /usr/bin/python3 ${PROJECT_SCRIPTS_DIR}/run_qack_static.py, /usr/bin/python3 ${PROJECT_SCRIPTS_DIR}/run_qack_dynamic.py

${SUDO_USER_NAME} ALL=(root) NOPASSWD: FAIRFLOW_MODPROBE, FAIRFLOW_RUN
EOF

echo "== Validating draft sudoers rule (not yet installed) =="
if ! visudo -c -f "$TMP_FILE"; then
  echo "Draft sudoers rule is INVALID — aborting, nothing was installed." >&2
  rm -f "$TMP_FILE"
  exit 1
fi
echo "Draft is syntactically valid."

if [[ "${1:-}" == "--check-only" ]]; then
  echo "== --check-only requested: stopping before any sudo/install step. =="
  rm -f "$TMP_FILE"
  exit 0
fi

echo "== Installing to ${RULE_FILE} (requires your sudo password once) =="
sudo install -o root -g root -m 0440 "$TMP_FILE" "$RULE_FILE"
rm -f "$TMP_FILE"

echo "== Re-validating the full sudoers database after install =="
sudo visudo -c

echo "== Done. Passwordless sudo is now scoped to EXACTLY: =="
echo "     modprobe tcp_bbr"
echo "     python3 ${PROJECT_SCRIPTS_DIR}/{run_smoketest,run_baseline,run_qack_static,run_qack_dynamic}.py (no args)"
echo "   Nothing else — including apt-get — was granted passwordless sudo."
